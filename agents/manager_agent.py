from agents.base_agent import BaseAgent
import json
class ManagerAgent(BaseAgent):

    def __init__(self):
        super().__init__(
            name="Manager Agent", 
            role="Project Manager",
            instructions=(
                "Understand the user's research request, "
                "break it into smaller tasks, and assign "
                "each task to the most suitable specialized agent."
            )
        )

    def execute(self, task: str) -> str:
        return self.create_plan(task)
    
    def create_plan(self, user_request: str) -> str:

        prompt = f"""
        You are a Manager Agent.

        Break the user's request into smaller tasks.

        Assign each task to the most suitable agent.

        Available agents:
        - research_agent
        - financial_agent
        - competitor_agent
        - writer_agent

        Return only valid JSON in this format:

        {{
            "tasks": [
                {{
                    "task_id": 1,
                    "agent": "research_agent",
                    "description": "Research market trends"
                }}
            ]
        }}

        User request: {user_request}
        """

        response = self.generate_response(prompt)

        plan = json.loads(response)

        if not self.validate_plan(plan):
            raise ValueError("Invalide execution plan generated by Manager Agent.")

        return plan

    def validate_plan(self, plan:dict) -> bool:

        available_agents = [
            "research_agent",
            "financial_agent",
            "competitor_agent",
            "writer_agent"
        ]

        if not plan.get("tasks"):
            return False

        task_ids = set()

        for task in plan["tasks"]:

            required_fields = ["task_id", "agent", "description"]

            for field in required_fields:
                if field not in task:
                    return False
            if task["task_id"] in task_ids:
                return False
            task_ids.add(task["task_id"])

            if not isinstance(task["agent"], str) or task["agent"] not in available_agents:
                return False

        return True